// Package frpx knows frp's config format (the TOML subset frp-console writes),
// its `verify` command and its local admin HTTP API.
package frpx

import (
	"bytes"
	"errors"
	"fmt"
	"io"
	"net/http"
	"os/exec"
	"path/filepath"
	"strconv"
	"strings"
	"time"
)

type PortRange struct {
	Single int `json:"single,omitempty"`
	Start  int `json:"start,omitempty"`
	End    int `json:"end,omitempty"`
}

type ProxySpec struct {
	Name          string   `json:"name"`
	Type          string   `json:"type"`
	LocalIP       string   `json:"localIP,omitempty"`
	LocalPort     int      `json:"localPort,omitempty"`
	RemotePort    int      `json:"remotePort,omitempty"`
	CustomDomains []string `json:"customDomains,omitempty"`
	SubDomain     string   `json:"subDomain,omitempty"`
	SecretKey     string   `json:"secretKey,omitempty"`
}

type ClientSpec struct {
	ServerAddr string      `json:"serverAddr"`
	ServerPort int         `json:"serverPort"`
	Token      string      `json:"token,omitempty"`
	WebPort    int         `json:"webPort,omitempty"`
	WebUser    string      `json:"webUser,omitempty"`
	WebPass    string      `json:"webPass,omitempty"`
	Proxies    []ProxySpec `json:"proxies"`
}

type ServerSpec struct {
	BindPort   int         `json:"bindPort"`
	Token      string      `json:"token,omitempty"`
	WebPort    int         `json:"webPort,omitempty"`
	WebUser    string      `json:"webUser,omitempty"`
	WebPass    string      `json:"webPass,omitempty"`
	AllowPorts []PortRange `json:"allowPorts,omitempty"`
}

var proxyTypes = map[string]bool{
	"tcp": true, "udp": true, "http": true, "https": true,
	"stcp": true, "xtcp": true, "sudp": true, "tcpmux": true,
}

func ConfigName(kind string) string {
	if kind == "server" {
		return "frps.toml"
	}
	return "frpc.toml"
}

func (s ClientSpec) Validate() error {
	if strings.TrimSpace(s.ServerAddr) == "" {
		return errors.New("serverAddr is required")
	}
	if !validPort(s.ServerPort) {
		return errors.New("serverPort must be 1-65535")
	}
	seen := map[string]bool{}
	for i, p := range s.Proxies {
		if strings.TrimSpace(p.Name) == "" {
			return fmt.Errorf("proxy #%d: name is required", i+1)
		}
		if seen[p.Name] {
			return fmt.Errorf("proxy %q: duplicate name", p.Name)
		}
		seen[p.Name] = true
		if !proxyTypes[p.Type] {
			return fmt.Errorf("proxy %q: unsupported type %q", p.Name, p.Type)
		}
		if !validPort(p.LocalPort) {
			return fmt.Errorf("proxy %q: localPort must be 1-65535", p.Name)
		}
		switch p.Type {
		case "tcp", "udp":
			if !validPort(p.RemotePort) {
				return fmt.Errorf("proxy %q: remotePort must be 1-65535", p.Name)
			}
		case "http", "https", "tcpmux":
			if len(p.CustomDomains) == 0 && strings.TrimSpace(p.SubDomain) == "" {
				return fmt.Errorf("proxy %q: customDomains or subDomain is required", p.Name)
			}
		}
	}
	if s.WebPort != 0 && !validPort(s.WebPort) {
		return errors.New("webPort must be 1-65535")
	}
	return nil
}

func (s ServerSpec) Validate() error {
	if !validPort(s.BindPort) {
		return errors.New("bindPort must be 1-65535")
	}
	if s.WebPort != 0 && !validPort(s.WebPort) {
		return errors.New("webPort must be 1-65535")
	}
	for _, r := range s.AllowPorts {
		if r.Single == 0 && r.Start == 0 && r.End == 0 {
			return errors.New("allowPorts entry needs single or start/end")
		}
		if r.Single != 0 && !validPort(r.Single) {
			return errors.New("allowPorts single must be 1-65535")
		}
		if r.Start != 0 || r.End != 0 {
			if !validPort(r.Start) || !validPort(r.End) || r.Start > r.End {
				return errors.New("allowPorts range must satisfy 0 < start <= end <= 65535")
			}
		}
	}
	return nil
}

func RenderClient(spec ClientSpec) []byte {
	var b strings.Builder
	b.WriteString("# generated by frp-console; safe to edit by hand\n")
	fmt.Fprintf(&b, "serverAddr = %s\n", quote(spec.ServerAddr))
	fmt.Fprintf(&b, "serverPort = %d\n", spec.ServerPort)
	if spec.Token != "" {
		fmt.Fprintf(&b, "auth.token = %s\n", quote(spec.Token))
	}
	if spec.WebPort > 0 {
		user, pass := spec.WebUser, spec.WebPass
		if user == "" {
			user = "admin"
		}
		b.WriteString("\nwebServer.addr = \"127.0.0.1\"\n")
		fmt.Fprintf(&b, "webServer.port = %d\n", spec.WebPort)
		fmt.Fprintf(&b, "webServer.user = %s\n", quote(user))
		fmt.Fprintf(&b, "webServer.password = %s\n", quote(pass))
		b.WriteString("store.path = \"./frpc.store.json\"\n")
	}
	for _, p := range spec.Proxies {
		b.WriteString("\n[[proxies]]\n")
		fmt.Fprintf(&b, "name = %s\n", quote(p.Name))
		fmt.Fprintf(&b, "type = %s\n", quote(p.Type))
		localIP := p.LocalIP
		if localIP == "" {
			localIP = "127.0.0.1"
		}
		fmt.Fprintf(&b, "localIP = %s\n", quote(localIP))
		fmt.Fprintf(&b, "localPort = %d\n", p.LocalPort)
		switch p.Type {
		case "tcp", "udp":
			fmt.Fprintf(&b, "remotePort = %d\n", p.RemotePort)
		case "http", "https", "tcpmux":
			if len(p.CustomDomains) > 0 {
				fmt.Fprintf(&b, "customDomains = %s\n", strList(p.CustomDomains))
			}
			if p.SubDomain != "" {
				fmt.Fprintf(&b, "subDomain = %s\n", quote(p.SubDomain))
			}
		}
		if p.SecretKey != "" && (p.Type == "stcp" || p.Type == "xtcp" || p.Type == "sudp") {
			fmt.Fprintf(&b, "secretKey = %s\n", quote(p.SecretKey))
		}
	}
	return []byte(b.String())
}

func RenderServer(spec ServerSpec) []byte {
	var b strings.Builder
	b.WriteString("# generated by frp-console; safe to edit by hand\n")
	fmt.Fprintf(&b, "bindPort = %d\n", spec.BindPort)
	if spec.Token != "" {
		fmt.Fprintf(&b, "auth.token = %s\n", quote(spec.Token))
	}
	if spec.WebPort > 0 {
		user, pass := spec.WebUser, spec.WebPass
		if user == "" {
			user = "admin"
		}
		b.WriteString("\nwebServer.addr = \"127.0.0.1\"\n")
		fmt.Fprintf(&b, "webServer.port = %d\n", spec.WebPort)
		fmt.Fprintf(&b, "webServer.user = %s\n", quote(user))
		fmt.Fprintf(&b, "webServer.password = %s\n", quote(pass))
	}
	var ranges []string
	for _, r := range spec.AllowPorts {
		switch {
		case r.Single > 0:
			ranges = append(ranges, fmt.Sprintf("{ single = %d }", r.Single))
		case r.Start > 0 && r.End >= r.Start:
			ranges = append(ranges, fmt.Sprintf("{ start = %d, end = %d }", r.Start, r.End))
		}
	}
	if len(ranges) > 0 {
		fmt.Fprintf(&b, "allowPorts = [%s]\n", strings.Join(ranges, ", "))
	}
	return []byte(b.String())
}

// Verify runs `frpc|frps verify -c <file>` from the config's own directory.
func Verify(bin, cfgPath string) error {
	cmd := exec.Command(bin, "verify", "-c", cfgPath)
	cmd.Dir = filepath.Dir(cfgPath)
	out, err := cmd.CombinedOutput()
	if err != nil {
		msg := strings.TrimSpace(string(out))
		if msg == "" {
			msg = err.Error()
		}
		return errors.New(msg)
	}
	return nil
}

// WebAuth extracts the dashboard port and credentials from a config file.
// It understands both dotted keys and a [webServer] table.
func WebAuth(cfg []byte) (port int, user, pass string) {
	section := ""
	for _, raw := range strings.Split(string(cfg), "\n") {
		line := strings.TrimSpace(stripComment(raw))
		if line == "" {
			continue
		}
		if strings.HasPrefix(line, "[") {
			section = strings.Trim(strings.Trim(line, "[]"), " ")
			continue
		}
		key, val, ok := strings.Cut(line, "=")
		if !ok {
			continue
		}
		key = strings.TrimSpace(key)
		val = strings.TrimSpace(val)
		if section != "" {
			key = section + "." + key
		}
		switch key {
		case "webServer.port":
			if n, err := strconv.Atoi(unquote(val)); err == nil {
				port = n
			}
		case "webServer.user":
			user = unquote(val)
		case "webServer.password":
			pass = unquote(val)
		}
	}
	return port, user, pass
}

var adminClient = &http.Client{Timeout: 4 * time.Second}

// Admin calls frp's local admin API, e.g. GET /api/status.
func Admin(port int, user, pass, method, path string, body []byte) ([]byte, error) {
	var rdr io.Reader
	if body != nil {
		rdr = bytes.NewReader(body)
	}
	req, err := http.NewRequest(method, fmt.Sprintf("http://127.0.0.1:%d%s", port, path), rdr)
	if err != nil {
		return nil, err
	}
	if user != "" {
		req.SetBasicAuth(user, pass)
	}
	if body != nil {
		req.Header.Set("Content-Type", "application/json")
	}
	resp, err := adminClient.Do(req)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()
	data, _ := io.ReadAll(io.LimitReader(resp.Body, 4<<20))
	if resp.StatusCode < 200 || resp.StatusCode > 299 {
		return data, fmt.Errorf("%s %s: %s %s", method, path, resp.Status, strings.TrimSpace(string(data)))
	}
	return data, nil
}

func quote(s string) string { return strconv.Quote(s) }

func strList(items []string) string {
	parts := make([]string, 0, len(items))
	for _, it := range items {
		parts = append(parts, quote(it))
	}
	return "[" + strings.Join(parts, ", ") + "]"
}

func validPort(p int) bool { return p > 0 && p <= 65535 }

func unquote(v string) string {
	if len(v) >= 2 && v[0] == '"' && v[len(v)-1] == '"' {
		if s, err := strconv.Unquote(v); err == nil {
			return s
		}
		return v[1 : len(v)-1]
	}
	if len(v) >= 2 && v[0] == '\'' && v[len(v)-1] == '\'' {
		return v[1 : len(v)-1]
	}
	return v
}

func stripComment(s string) string {
	var quote byte
	for i := 0; i < len(s); i++ {
		c := s[i]
		if quote != 0 {
			if c == '\\' && quote == '"' {
				i++
				continue
			}
			if c == quote {
				quote = 0
			}
			continue
		}
		switch c {
		case '"', '\'':
			quote = c
		case '#':
			return s[:i]
		}
	}
	return s
}
